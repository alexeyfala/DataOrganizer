namespace Shared.Common;

/// <summary>
/// File extensions the application relies on, each with the leading dot.
/// </summary>
public static class KnownFileExtensions
{
	#region Data
	/// <summary>
	/// The extension of a Json file.
	/// </summary>
	public const string Json = ".json";

	/// <summary>
	/// The extension of a SQLite database file.
	/// </summary>
	public const string Sqlite = ".sqlite";

	/// <summary>
	/// The extension of a plain text file.
	/// </summary>
	public const string Txt = ".txt";

	/// <summary>
	/// The extension of an Xml file.
	/// </summary>
	public const string Xml = ".xml";
	#endregion
}
